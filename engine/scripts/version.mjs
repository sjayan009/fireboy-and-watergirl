import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { resolve, relative } from "node:path";
import { fileURLToPath } from "node:url";
const root = fileURLToPath(new URL("../src/", import.meta.url));
const walk = dir => readdirSync(dir, { withFileTypes: true }).flatMap(e => e.isDirectory() ? walk(resolve(dir, e.name)) : [resolve(dir, e.name)]);
const files = ["game", "flash", "box2d"].flatMap(dir => walk(resolve(root, dir)));
files.push(...["net/gamehost.ts", "net/hash.ts", "net/protocol.ts", "verified.ts"].map(p => resolve(root, p)));
const hash = createHash("sha256");
for (const file of files.sort()) hash.update(relative(root, file).replaceAll("\\", "/")).update("\0").update(readFileSync(file, "utf8").replaceAll("\r\n", "\n")).update("\0");
writeFileSync(resolve(root, "version.ts"), `// Generated by scripts/version.mjs; replay rules identify their exact build.\nexport const ENGINE_VERSION = "temple-${hash.digest("hex").slice(0, 32)}";\n`);
