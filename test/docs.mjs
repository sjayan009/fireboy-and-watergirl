/**
 * The things the prose says, checked against the things that exist.
 *
 * Documentation drift is not usually worth a test. It became worth one here
 * because the drifting prose is a RUNBOOK: the Supabase README and the workflow
 * comments described a migration `0013_open_signup` and "thirteen migrations"
 * for a directory that ended at `0012`, and the app README pointed at
 * `app/dist` for a build that writes to the repository root. Those are the two
 * sentences somebody reads during a release or an incident, and each of them
 * sent the reader to a place that was not there.
 *
 * Three questions, all of them mechanical:
 *
 *   * does every migration filename mentioned anywhere actually exist?
 *   * does the documented build output match what the build config says?
 *   * is any generated Python bytecode tracked?
 *
 * Deliberately not a spell-check on the prose. The rule is "a name in the docs
 * resolves to a thing", which is narrow enough to have no false positives and
 * is exactly the class of error that was found.
 */
import { readFileSync, readdirSync, existsSync, statSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { dirname, join, resolve } from "node:path";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");

let failures = 0;
function check(what, got, want) {
  const ok = JSON.stringify(got) === JSON.stringify(want);
  if (!ok) failures++;
  console.log(`  ${ok ? "ok  " : "FAIL"} ${what}: ${JSON.stringify(got)}` +
              (ok ? "" : ` (expected ${JSON.stringify(want)})`));
}

/** Every file whose prose is operational: read during a release or an outage. */
const PROSE = [
  "README.md",
  "app/README.md",
  "supabase/README.md",
  "engine/PORT.md",
  ".github/workflows/fast.yml",
  ".github/workflows/full.yml",
  ".github/workflows/deployed.yml",
  ".github/workflows/keepalive.yml",
];

console.log("every migration the docs name exists");
{
  const have = new Set(readdirSync(join(ROOT, "supabase/migrations"))
    .filter((f) => f.endsWith(".sql")));
  const missing = [];
  for (const file of PROSE) {
    const path = join(ROOT, file);
    if (!existsSync(path)) { missing.push(`${file} (the doc itself)`); continue; }
    const text = readFileSync(path, "utf8");
    // `0013_open_signup`, `0016_progress_writes.sql`, and the bare-number form
    // the comments also use.
    for (const m of text.matchAll(/\b(\d{4}_[a-z0-9_]+)(\.sql)?\b/g)) {
      if (!have.has(m[1] + ".sql")) missing.push(`${file}: ${m[1]}`);
    }
  }
  check(`${have.size} migrations, and every reference resolves`, missing, []);
}

console.log("\nthe documented build output is where the build writes");
{
  const config = readFileSync(join(ROOT, "app/vite.config.ts"), "utf8");
  // `outDir: resolve(ROOT, "dist")` -- the repository's dist, not app/dist.
  const m = config.match(/outDir:\s*resolve\(ROOT,\s*"([^"]+)"\)/);
  check("vite.config names an output directory", !!m, true);
  const out = m ? m[1] : "";
  check("and it is the repository root's dist", out, "dist");

  const readme = readFileSync(join(ROOT, "app/README.md"), "utf8");
  check("the app README does not point at app/dist",
        /\bapp\/dist\b/.test(readme), false);
}

console.log("\nno generated bytecode is tracked");
{
  let tracked = [];
  try {
    tracked = execFileSync("git", ["ls-files"], { cwd: ROOT, encoding: "utf8" })
      .split("\n").filter(Boolean);
  } catch {
    console.log("  (not a git checkout -- skipping)");
  }
  if (tracked.length) {
    const junk = tracked.filter((p) =>
      /(^|\/)__pycache__\//.test(p) || /\.py[cod]$/.test(p));
    check("no __pycache__ or .pyc in the index", junk, []);
  }
}

console.log("\nthe pinned database certificate is there and is a certificate");
{
  const ca = join(ROOT, "supabase/certs/prod-ca-2021.crt");
  check("the file exists", existsSync(ca), true);
  if (existsSync(ca)) {
    const text = readFileSync(ca, "utf8");
    check("and looks like PEM", text.startsWith("-----BEGIN CERTIFICATE-----"),
          true);
    check("and is not empty", statSync(ca).size > 500, true);
  }
}

console.log("\n" + (failures === 0 ? "DOCS PASSED" : `DOCS FAILED (${failures})`));
process.exit(failures === 0 ? 0 : 1);
