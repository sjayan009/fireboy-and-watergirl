"""Emit TypeScript classes for the SWF library symbols the game constructs.

Frame counts and named children come from the SWF itself, so the ported logic
sees the same scene graph the original did -- which matters because level.as
reads it back (door `currentFrame`, lever `light`, character `mc_1`..`mc_5`).
"""
import json
import math
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
SYMS = os.path.join(HERE, "..", "extracted", "symbols.json")
SPRITES = os.path.join(HERE, "..", "extracted", "assets", "sprites.json")
TEXT = os.path.join(HERE, "..", "extracted", "assets", "text.json")
AS3 = os.path.join(HERE, "..", "extracted", "as3", "scripts")
OUT = os.path.join(HERE, "..", "engine", "src", "flash", "symbols.ts")

HEADER = '''// GENERATED by tools/gen_symbols.py from the SWF library.
// Do not edit by hand -- re-run the generator instead.
//
// Frame counts and named children are the SWF's own, because level.as reads
// display state back as game state (see flash.ts).

import { MovieClip, Sound, TextField } from "./flash.js";

interface ChildSpec {
  name: string;
  symbol: string | null;
  /** SWF character id. Many child clips (FireBoy's poses) are unnamed in the
   *  library, so the id is the only way to find their art. */
  id?: number;
  /** Initial transform from the SWF placement matrix. Game code may override
   *  it at runtime -- FireBoy flips a pose with mc_4.scaleX = -0.135. */
  t?: { x: number; y: number; sx: number; sy: number; rot: number };
  /** "text" for a DefineEditText character -- built as a TextField. */
  kind?: "text";
}

/**
 * Instance names are NOT unique. MainMenu places eight different clips all
 * called "node_1", so matching a child to its placement by name hands every
 * one of them the first placement -- which drew the real level-1 node at
 * x = -235, off the side of the stage, and left an empty socket on the map.
 * Children carry their placement index instead.
 */
const PLACE = "__place";

/** One DefineEditText character, from extract_text.py. */
interface TextSpec {
  bounds: { x: number; y: number; w: number; h: number };
  size?: number;
  fontId?: number;
  fontName?: string;
  color?: number;
  align?: string;
  multiline?: boolean;
  initialText?: string;
  /** extract_text.py records the whole tag; the rest is carried, not used. */
  [key: string]: any;
}
interface SymbolSpec {
  frames: number;
  children: ChildSpec[];
  /** 1-based frames whose SWF frame script calls stop(). */
  stopFrames?: number[];
  /**
   * The child that MASKS its siblings, from the SWF's ClipDepth.
   *
   * Nothing in the ActionScript says a mask exists -- `level.as` just sets
   * `ropeMask.height` and expects the rope to grow with it. Without this the
   * chain art slides around at its authored length instead of stretching.
   */
  clipMask?: string;
}

export const SYMBOLS: Record<string, SymbolSpec> = SPEC_JSON;

/** character id -> frame count, for clips with no library name. */
export const SPRITE_FRAMES: Record<number, number> = FRAMES_JSON;

/**
 * character id -> DefineEditText properties.
 *
 * The renderer needs these to draw the field: the game only ever sets `.text`,
 * exactly as the original did, and everything about how it looks -- face, size,
 * colour, alignment, box -- comes from the SWF.
 */
export const TEXT_FIELDS: Record<number, TextSpec> = TEXT_JSON;

/** Build a TextField seeded from its DefineEditText character. */
function makeTextField(id: number): TextField {
  const t = new TextField();
  const spec = TEXT_FIELDS[id];
  if (spec) {
    t.bounds = spec.bounds;
    if (spec.size != null) t.size = spec.size;
    if (spec.fontId != null) t.fontId = spec.fontId;
    if (spec.color != null) t.textColor = spec.color;
    if (spec.align) t.align = spec.align as TextField["align"];
    t.multiline = !!spec.multiline;
    // Flash shows the authored text until the game overwrites it, and some
    // fields (the menu map's per-level times) are never written on a fresh
    // save -- so the initial text is what is actually on screen.
    t.text = spec.initialText ?? "";
  }
  (t as any).spriteId = id;
  return t;
}

/**
 * Apply a child's initial transform from the SWF placement matrix, and record
 * it. The renderer compares against this snapshot to tell an untouched child
 * (use the manifest's per-frame matrix, so a running head can bob) from one the
 * game has driven (`mc_4.scaleX = -0.135` flips a pose).
 */
function seed(child: MovieClip | TextField,
             t: NonNullable<ChildSpec["t"]>): void {
  child.x = t.x;
  child.y = t.y;
  child.scaleX = t.sx;
  child.scaleY = t.sy;
  child.rotation = t.rot;
  (child as any).__seed = { x: t.x, y: t.y, sx: t.sx, sy: t.sy, rot: t.rot };
}

/** Build a child clip, by library name when it has one, else by character id. */
function makeChild(c: ChildSpec, depth: number): MovieClip | TextField {
  if (c.kind === "text" && c.id != null) return makeTextField(c.id);
  if (c.symbol) return makeSymbol(c.symbol, depth);
  const frames = c.id != null ? (SPRITE_FRAMES[c.id] ?? 1) : 1;
  const mc = new MovieClip("", frames);
  if (c.id != null) (mc as any).spriteId = c.id;
  return mc;
}

/**
 * Hook up a ClipDepth mask: the named child clips its siblings, in the
 * clip's own coordinate space rather than the parent's.
 */
function applyClipMask(mc: MovieClip, spec: SymbolSpec): void {
  if (!spec.clipMask) return;
  const mask = (mc as any)[spec.clipMask];
  if (!mask) return;
  mask.isMask = true;                 // a mask is never painted, only clips
  (mc as any).__clipMask = mask;
}

/** Build a symbol by library name, including its named children. */
export function makeSymbol(name: string, depth = 0): MovieClip {
  const spec = SYMBOLS[name];
  const mc = new MovieClip(name, spec ? spec.frames : 1,
                           spec ? spec.stopFrames : undefined);
  if (spec && depth < 8) {
    spec.children.forEach((c, i) => {
      const child = makeChild(c, depth + 1);
      child.name = c.name;
      (child as any)[PLACE] = i;
      if (c.id != null) (child as any).spriteId = c.id;
      if (c.t) seed(child, c.t);
      mc.addChild(child);
      (mc as any)[c.name] = child;
    });
    applyClipMask(mc, spec);
  }
  return mc;
}

/** Base for the generated library classes. */
export class LibraryClip extends MovieClip {
  constructor(symbol: string) {
    const spec = SYMBOLS[symbol];
    super(symbol, spec ? spec.frames : 1, spec ? spec.stopFrames : undefined);
    if (spec) {
      spec.children.forEach((c, i) => {
        const child = makeChild(c, 1);
        child.name = c.name;
        (child as any)[PLACE] = i;
        if (c.id != null) (child as any).spriteId = c.id;
        if (c.t) seed(child, c.t);
        this.addChild(child);
        (this as any)[c.name] = child;
      });
      applyClipMask(this, spec);
    }
  }
}
'''


def main():
    syms = json.load(open(SYMS))

    # DefineEditText characters, from extract_text.py. A child whose character
    # is one of these becomes a TextField rather than an empty MovieClip.
    text_fields = {}
    if os.path.exists(TEXT):
        text_fields = json.load(open(TEXT))["fields"]

    # which symbols does the game actually construct?
    used = set()
    for fn in ("level.as", "Game.as", "ContactListener.as"):
        p = os.path.join(AS3, fn)
        if os.path.exists(p):
            src = open(p, encoding="utf-8", errors="replace").read()
            used |= set(re.findall(r"new\s+([A-Za-z_]\w*)\s*\(", src))

    # placement matrices recovered from the sprite export, so a named child
    # starts life with the transform the SWF gave it
    # Keyed by PLACEMENT ORDER, not by name. MainMenu places eight separate
    # clips all named "node_1" (characters 569, 571, 573, 607...); keying by
    # name collapsed seven of them onto one character id and one matrix, so
    # most of the level-map decoration was drawn with the wrong art in the
    # wrong place. Both extractors walk the same PlaceObject tags in the same
    # order, so the lists line up index for index.
    placements = {}
    frames_by_id = {}
    if os.path.exists(SPRITES):
        sprites = json.load(open(SPRITES))
        for nm, cid in sprites["byName"].items():
            geom = sprites["sprites"][str(cid)]["geom"]
            if geom and geom[0]["children"]:
                placements[nm] = geom[0]["children"]
        frames_by_id = {int(k): v["frames"]
                        for k, v in sprites["sprites"].items()}

    def stop_frames(sym):
        """1-based frames whose SWF frame script calls stop().

        Flash plays a placed clip automatically; these scripts are what hold
        the exit doors, levers and tutorial pages on a single frame.
        """
        rel = sym.replace(".", os.sep) + ".as"
        path = os.path.join(AS3, rel)
        if not os.path.exists(path):
            return []
        src = open(path, encoding="utf-8", errors="replace").read()
        m = re.search(r"addFrameScript\(([^)]*)\)", src)
        if not m:
            return []
        parts = [x.strip() for x in m.group(1).split(",")]
        out = []
        for i in range(0, len(parts) - 1, 2):
            try:
                idx = int(parts[i])
            except ValueError:
                continue
            handler = parts[i + 1]
            body = re.search(
                r"function\s+" + re.escape(handler) +
                r"\s*\(\)[^{]*\{(.*?)^      \}",
                src, re.S | re.M)
            if body and "stop();" in body.group(1):
                out.append(idx + 1)
        return out

    def align(sym, children):
        """Pair each SWF child with its SVG placement, or None.

        Both lists are in placement order, but the SVG list can be SHORTER: a
        mask is never rendered, so JPEXS omits it, and `Connector` is
        [ropeMask, chain] in the SWF but just [chain] in the export. So walk
        them together and consume a placement only when the names agree, which
        keeps the pairing positional -- the thing that matters, because eight
        of MainMenu's children are all called "node_1" and a name lookup would
        hand every one of them the first placement.
        """
        place = placements.get(sym) or []
        out = []
        j = 0
        for c in children:
            if j < len(place) and place[j]["name"] == c["name"]:
                out.append(place[j])
                j += 1
            else:
                out.append(None)
        if j < len(place):
            raise SystemExit(
                "%s: sprites.json has placements the SWF does not name (%s) -- "
                "the two extractors have gone out of step"
                % (sym, [p["name"] for p in place[j:]]))
        return out

    def child_spec(sym, c, place):
        out = {"name": c["name"], "symbol": c["symbol"]}
        cid = place["id"] if place else None
        if cid is None:
            cid = c.get("id")
        if cid is not None:
            out["id"] = cid
        if cid is not None and str(cid) in text_fields:
            # a DefineEditText: the renderer draws it as text, not as art
            out["kind"] = "text"
        m = place["m"] if place else None
        if m:
            a, b, cc, d, tx, ty = m
            out["t"] = {
                "x": tx, "y": ty,
                "sx": math.copysign(math.hypot(a, b), a) or 1.0,
                "sy": math.copysign(math.hypot(cc, d), d) or 1.0,
                "rot": math.degrees(math.atan2(b, a)),
            }
        return out

    spec = {}
    for k, v in syms.items():
        entry = {"frames": v["frames"],
                 "children": [child_spec(k, c, pl)
                              for c, pl in zip(v["children"],
                                               align(k, v["children"]))]}
        sf = stop_frames(k)
        if sf:
            entry["stopFrames"] = sf
        if v.get("clipMask"):
            entry["clipMask"] = v["clipMask"]
        spec[k] = entry

    # only the characters actually placed as children need shipping
    used_text = {int(c["id"]): text_fields[str(c["id"])]
                 for v in spec.values() for c in v["children"]
                 if c.get("kind") == "text"}
    out = [HEADER
           .replace("SPEC_JSON", json.dumps(spec, indent=1, sort_keys=True))
           .replace("FRAMES_JSON", json.dumps(frames_by_id, sort_keys=True))
           .replace("TEXT_JSON", json.dumps(used_text, sort_keys=True))]
    print("text fields      : %d of %d DefineEditText characters are placed"
          % (len(used_text), len(text_fields)))

    sound_names = {k for k in syms if k.endswith("_Sound")} | {
        "Smash", "Finish1", "Finish2"}

    # PauseMenu, Recuento and GameOvero are library symbols that also carry
    # real logic (the sliding tray, the easing results board), so gen_game.py
    # generates them from their .as files instead -- extending LibraryClip so
    # they still get the symbol's frames and named children.
    shell_classes = {"PauseMenu", "Recuento", "GameOvero", "deadFire",
                     "WaterGirlStairs"}

    emitted = []
    for name in sorted(syms):
        if name in shell_classes:
            continue
        if not re.match(r"^[A-Za-z_]\w*$", name):
            continue          # timeline-internal names like Foo_fla.Bar_12
        if name not in used:
            continue
        if name in sound_names:
            out.append('export class %s extends Sound {\n'
                       '  constructor() { super("%s"); }\n}' % (name, name))
        else:
            out.append('export class %s extends LibraryClip {\n'
                       '  constructor() { super("%s"); }\n}' % (name, name))
        emitted.append(name)

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w", encoding="utf-8").write("\n\n".join(out) + "\n")
    print("emitted %d symbol classes (of %d in the library)"
          % (len(emitted), len(syms)))
    missing = sorted(n for n in used if n not in syms)
    print("constructed by the game but not SWF symbols: %s"
          % (", ".join(missing) if missing else "none"))
    print("wrote %s" % os.path.abspath(OUT))


if __name__ == "__main__":
    main()
