"""Transliterate decompiled Box2DFlash 2.0.2 AS3 into TypeScript.

AS3 is ECMAScript, so this is close to a syntactic rewrite rather than a
translation. Everything is emitted into ONE module: Box2D's class graph is
densely circular (b2World <-> b2Body <-> b2Shape <-> b2Contact ...) and ES
module cycles would break `extends` at evaluation time.

Four things AS3 permits that TypeScript does not, all handled here:

  * unqualified instance members (`m_flags` for `this.m_flags`). Safe to
    rewrite automatically because the decompiler names every local `_locN_`
    and every parameter `paramN`, so no member name can be shadowed.
  * unqualified statics, including ones inherited from a base class.
  * static initialisers that construct classes declared later in the file
    -> all static initialisers are hoisted to the end.
  * `super()` in a class with no base type.

Subclasses are emitted after their base classes (topological sort).
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "extracted", "as3", "scripts", "Box2D")
OUT = os.path.join(HERE, "..", "engine", "src", "box2d", "box2d.ts")

TYPES = {
    "Number": "number", "int": "number", "uint": "number",
    "Boolean": "boolean", "String": "string", "void": "void",
    "*": "any", "Object": "any", "Array": "any[]", "Function": "any",
    # Flash-only types, reachable solely from b2DebugDraw
    "Sprite": "any", "Graphics": "any", "DisplayObject": "any",
    # shell types with no shim of their own: buttons are out of scope, and
    # SharedObject is replaced by the SaveStore interface in save.ts
    "SimpleButton": "any", "SharedObject": "any", "ContextMenu": "any",
    "Loader": "any", "URLRequest": "any", "TextField": "any",
}

HEADER = '''// GENERATED by tools/as3_to_ts.py from the decompiled Box2DFlash 2.0.2
// that shipped inside "Fireboy & Watergirl - The Forest Temple.swf".
// Do not edit by hand -- re-run the generator instead.

// Math.sin/cos/atan2 are only "implementation-approximated" in ECMAScript and
// differ per engine, which would desync lockstep netcode. See dettrig.ts.
import { detSin, detCos, detAtan2 } from "./dettrig.js";

/** AS3 `int(x)`: truncate and wrap to 32-bit signed -- `x | 0` is exactly that. */
function i32(x: number): number { return x | 0; }
/** AS3 `uint(x)`: truncate and wrap to 32-bit unsigned. */
function u32(x: number): number { return x >>> 0; }
'''


def ts_type(t):
    return TYPES.get(t.strip(), t.strip())


class ClassInfo:
    def __init__(self, name, base, is_interface):
        self.name = name
        self.base = base
        self.is_interface = is_interface
        self.statics = {}     # name -> (type, init or None)
        self.fields = []      # (name, type, init or None)
        self.methods = {}     # instance method names
        self.smethods = {}    # static method names
        self.body = []        # method/constructor source lines
        self.intfields = {}   # field name -> 'int' | 'uint'


RE_CLASS = re.compile(
    r"^\s*public\s+(?:final\s+|dynamic\s+)?(class|interface)\s+(\w+)"
    r"(?:\s+extends\s+([\w.]+))?(?:\s+implements\s+[\w.,\s]+)?\s*$")
RE_STATIC = re.compile(
    r"^\s*(?:public|private|protected|internal)?\s*static\s+(?:const|var)\s+"
    r"(\w+)\s*:\s*([\w.*\[\]]+)\s*(?:=\s*(.+?))?\s*;\s*$")
RE_FIELD = re.compile(
    r"^\s*(?:public|private|protected|internal)?\s*var\s+"
    r"(\w+)\s*:\s*([\w.*\[\]]+)\s*(?:=\s*(.+?))?\s*;\s*$")
RE_FUNC = re.compile(
    r"^(\s*)(?:(override)\s+)?(?:(public|private|protected|internal)\s+)?"
    r"(?:(static)\s+)?function\s+(?:(get|set)\s+)?(\w+)\s*\((.*?)\)"
    r"(?:\s*:\s*([\w.*\[\]]+))?\s*$")
RE_LOCAL = re.compile(
    r"^(\s*)var\s+(\w+)\s*:\s*([\w.*\[\]]+)\s*(?:=\s*(.+?))?\s*;\s*$")


def convert_params(p):
    if not p.strip():
        return ""
    parts, depth, cur = [], 0, ""
    for ch in p:
        if ch in "([{":
            depth += 1
        elif ch in ")]}":
            depth -= 1
        if ch == "," and depth == 0:
            parts.append(cur)
            cur = ""
        else:
            cur += ch
    if cur.strip():
        parts.append(cur)
    out = []
    for a in parts:
        a = a.strip()
        if a.startswith("..."):
            out.append("...rest: any[]")
            continue
        m = re.match(r"^(\w+)\s*:\s*([\w.*\[\]]+)\s*(?:=\s*(.+))?$", a)
        if m:
            nm, ty, dv = m.group(1), ts_type(m.group(2)), m.group(3)
            out.append("%s: %s = %s" % (nm, ty, dv) if dv
                       else "%s: %s" % (nm, ty))
        else:
            out.append(a)
    return ", ".join(out)


def parse_file(path):
    lines = open(path, encoding="utf-8", errors="replace").read().split("\n")
    ci = None
    depth = 0
    for raw in lines:
        line = raw.rstrip()
        s = line.strip()
        if s.startswith("import ") or s.startswith("package"):
            continue
        m = RE_CLASS.match(line)
        if m and ci is None:
            kind, name, base = m.group(1), m.group(2), m.group(3)
            ci = ClassInfo(name, base.split(".")[-1] if base else None,
                           kind == "interface")
            continue
        if ci is None:
            continue
        if s == "{":
            depth += 1
            if depth == 1:
                continue
        # `});` and `};` close an anonymous function passed as an argument --
        # Game.as hands two to addEventListener in GameOver and one in Recuent.
        # Their opening `{` counts toward depth, so their closing line has to
        # as well, or depth leaks upward and the class's own closing brace is
        # emitted into the body.
        if s.startswith("}"):
            depth -= 1
            if depth <= 0:
                continue

        m = RE_STATIC.match(line)
        if m and depth == 1:
            ci.statics[m.group(1)] = (ts_type(m.group(2)), m.group(3))
            continue

        m = RE_FIELD.match(line)
        if m and depth == 1:
            ci.fields.append((m.group(1), ts_type(m.group(2)), m.group(3)))
            if m.group(2).strip() in ("int", "uint"):
                ci.intfields[m.group(1)] = m.group(2).strip()
            continue

        m = RE_FUNC.match(line)
        if m:
            indent, _ov, vis, st, acc, nm, params, ret = m.groups()
            params = convert_params(params)
            ret = ts_type(ret) if ret else None
            vis = "" if vis in ("public", "internal", None) else vis + " "
            stat = "static " if st else ""
            if nm == ci.name and not st and not acc:
                ci.body.append(("sig", "%sconstructor(%s) {" % (indent, params)))
                continue
            if st:
                ci.smethods[nm] = None
            else:
                ci.methods[nm] = None
            if acc:
                ci.body.append(("sig", "%s%s%s%s %s(%s)%s {" % (
                    indent, vis, stat, acc, nm, params,
                    ": " + ret if ret and acc == "get" else "")))
            else:
                ci.body.append(("sig", "%s%s%s%s(%s)%s {" % (
                    indent, vis, stat, nm, params,
                    ": " + ret if ret else "")))
            continue

        if re.match(r"^\s*\{\s*$", line) and ci.body and \
                ci.body[-1][1].rstrip().endswith("{"):
            continue

        m = RE_LOCAL.match(line)
        if m:
            indent, nm, ty, init = m.groups()
            kind = "idecl:%s:%s" % (nm, ty.strip())                 if ty.strip() in ("int", "uint") else "code"
            ci.body.append((kind, "%svar %s: %s%s;" % (
                indent, nm, ts_type(ty), " = " + init if init else "")))
            continue

        ci.body.append(("code", line))
    return ci



def coerce_int_assignments(body, intfields):
    """AS3 coerces on every assignment to an `int`/`uint` variable, so
    `var i:int = (lo + hi) / 2` truncates. TypeScript's `number` does not,
    which silently turns array indices into fractions. Re-apply the coercion.

    The decompiler declares all locals at the top of each function, so one
    forward pass with a per-function scope is enough.
    """
    out = []
    scope = dict(intfields)
    for kind, line in body:
        if kind == "sig":
            scope = dict(intfields)
            out.append((kind, line))
            continue
        if kind.startswith("idecl:"):
            _, nm, ty = kind.split(":")
            scope[nm] = ty
            kind = "code"
        for nm, ty in scope.items():
            fn = "i32" if ty == "int" else "u32"
            e = re.escape(nm)
            m = re.match(r"^(\s*)%s\s*=(?!=)\s*(.+);\s*$" % e, line)
            if m:
                line = "%s%s = %s(%s);" % (m.group(1), nm, fn, m.group(2))
                break
            m = re.match(r"^(\s*)%s\s*([+\-*/])=\s*(.+);\s*$" % e, line)
            if m:
                line = "%s%s = %s(%s %s (%s));" % (
                    m.group(1), nm, fn, nm, m.group(2), m.group(3))
                break
        out.append((kind, line))
    return out


def split_code_strings(text):
    """Split into (is_code, chunk) runs, isolating string literals/comments.

    Every rewrite here is a regex over identifiers, so it MUST NOT run inside a
    string literal. Getting this wrong is silent and nasty: `userData.name =
    "pers1"` became `= "this.pers1"` because `pers1` is a field of `level`, and
    the resulting mismatch stopped diamonds from ever being collected.
    """
    out = []
    i = start = 0
    n = len(text)
    while i < n:
        c = text[i]
        if c == '"' or c == "'":
            out.append((True, text[start:i]))
            j = i + 1
            while j < n:
                if text[j] == "\\":
                    j += 2
                    continue
                if text[j] == c:
                    j += 1
                    break
                j += 1
            out.append((False, text[i:j]))
            i = start = j
            continue
        if c == "/" and i + 1 < n and text[i + 1] == "/":
            out.append((True, text[start:i]))
            j = text.find("\n", i)
            j = n if j < 0 else j
            out.append((False, text[i:j]))
            i = start = j
            continue
        if c == "/" and i + 1 < n and text[i + 1] == "*":
            out.append((True, text[start:i]))
            j = text.find("*/", i + 2)
            j = n if j < 0 else j + 2
            out.append((False, text[i:j]))
            i = start = j
            continue
        i += 1
    out.append((True, text[start:]))
    return out


def on_code(text, fn):
    """Apply `fn` to the code parts of `text`, leaving strings/comments alone."""
    return "".join(fn(chunk) if is_code else chunk
                   for is_code, chunk in split_code_strings(text))


def rewrite_calls(text, random_to=None):
    """AS3 casts -> helpers, and engine-dependent math -> deterministic math.

    sin/cos/atan2/acos and pow are all "implementation-approximated" in
    ECMAScript, so two browsers may disagree in the last ulp. acos matters
    most: it feeds SetXForm in CreatRoman, so it lands in the state digest
    and a disagreement there is a real desync, not a cosmetic one.

    `random_to` replaces `Math.random()` with a seeded generator. It is
    passed only for the game code -- Box2D's b2Random/b2RandomRange are
    library utilities this game never calls.

    The lookbehind keeps `b2Math.` untouched -- only a bare `Math.` call
    is rewritten.
    """
    def f(s):
        s = re.sub(r"(?<![\w.])int\(", "i32(", s)
        s = re.sub(r"(?<![\w.])uint\(", "u32(", s)
        s = re.sub(r"(?<![\w.])Math\.sin\(", "detSin(", s)
        s = re.sub(r"(?<![\w.])Math\.cos\(", "detCos(", s)
        s = re.sub(r"(?<![\w.])Math\.atan2\(", "detAtan2(", s)
        # AS3 `function():*` -> an arrow function, for two reasons: the `*`
        # reads as a JSDoc type in TS, and an anonymous function in AS3
        # captures the LEXICAL `this`. Game.as leans on that -- the results
        # board's back button is
        #     ToMenuBtn.addEventListener(CLICK, function():* { EndGame(); })
        # where EndGame belongs to the Game, not to the button the listener is
        # attached to. A plain `function` would be called with the button as
        # `this` and the click would do nothing.
        s = s.replace("function():*", "(): any =>")
        s = re.sub(r"(?<![\w.])Math\.acos\(", "detAcos(", s)
        s = re.sub(r"(?<![\w.])Math\.pow\(", "detPow(", s)
        if random_to:
            s = re.sub(r"(?<![\w.])Math\.random\(\)", random_to, s)
        # AS3 type test -> JS. Only the game code uses it; Box2D does not.
        s = re.sub(r"(?<![\w.$])is\s+([A-Za-z_]\w*)", r"instanceof \1", s)
        return s

    return on_code(text, f)


def qualify(text, names, prefix_of):
    """Prefix bare identifiers in `names`, skipping already-qualified ones."""
    if not names:
        return text
    pat = re.compile(r"(?<![\w.$])(%s)(?![\w$])"
                     % "|".join(sorted(map(re.escape, names), key=len,
                                       reverse=True)))
    return on_code(
        text, lambda s: pat.sub(lambda m: prefix_of(m.group(1)) + m.group(1), s))


def main():
    files = []
    for d, _, fs in os.walk(SRC):
        files += [os.path.join(d, f) for f in fs if f.endswith(".as")]
    classes = {}
    for f in sorted(files):
        ci = parse_file(f)
        if ci:
            classes[ci.name] = ci
    print("parsed %d classes from %d files" % (len(classes), len(files)))

    def ancestors(n):
        out, cur = [], classes.get(n)
        while cur and cur.base and cur.base in classes:
            out.append(cur.base)
            cur = classes[cur.base]
        return out

    # resolve which class owns each visible static / instance member
    static_owner, inst_members = {}, {}
    for n, ci in classes.items():
        so = {s: n for s in ci.statics}
        so.update({s: n for s in ci.smethods})
        im = set(f[0] for f in ci.fields) | set(ci.methods)
        for a in ancestors(n):
            for s in classes[a].statics:
                so.setdefault(s, a)
            for s in classes[a].smethods:
                so.setdefault(s, a)
            im |= set(f[0] for f in classes[a].fields) | set(classes[a].methods)
        static_owner[n] = so
        inst_members[n] = im - set(so) - set(classes)

    order, seen = [], set()

    def visit(n):
        if n in seen or n not in classes:
            return
        seen.add(n)
        if classes[n].base in classes:
            visit(classes[n].base)
        order.append(n)

    for n in sorted(classes):
        visit(n)

    out, tail = [HEADER], []
    for n in order:
        ci = classes[n]
        so, im = static_owner[n], inst_members[n]
        ext = " extends %s" % ci.base if ci.base in classes else ""
        out.append("\nexport %s %s%s {" %
                   ("interface" if ci.is_interface else "class", n, ext))
        for s, (ty, _) in ci.statics.items():
            out.append("  static %s: %s;" % (s, ty))
        for fn, ty, init in ci.fields:
            if init:
                init = qualify(init, so.keys(), lambda x: so[x] + ".")
                init = rewrite_calls(init)
            out.append("  %s: %s%s;" % (fn, ty, " = " + init if init else ""))

        if ext:
            for i, (kind, line) in enumerate(ci.body):
                if kind != "sig" or "constructor(" not in line:
                    continue
                for j in range(i + 1, len(ci.body)):
                    if ci.body[j][0] == "sig":
                        break
                    if re.match(r"^\s*super\(", ci.body[j][1]):
                        sup = ci.body.pop(j)
                        ci.body.insert(i + 1, sup)
                        break
                break
        intf = dict(ci.intfields)
        for a in ancestors(n):
            intf.update(classes[a].intfields)
        ci.body = coerce_int_assignments(ci.body, intf)

        parts = []
        for kind, line in ci.body:
            if kind == "code":
                line = qualify(line, so.keys(), lambda s: so[s] + ".")
                line = qualify(line, im, lambda s: "this.")
            parts.append(line)
        body = "\n".join(parts)
        if not ext:
            body = re.sub(r"^[ \t]*super\([^)]*\);[ \t]*$", "", body,
                          flags=re.M)
        body = rewrite_calls(body)
        out.append(body)
        out.append("}")

        for s, (ty, init) in ci.statics.items():
            if init is None:
                continue
            e = qualify(init, so.keys(), lambda x: so[x] + ".")
            e = rewrite_calls(e)
            tail.append((n, s, e))

    # Hoisted initialisers must run in dependency order, not class order:
    # b2BroadPhase.b2_invalid reads b2Settings.USHRT_MAX, and b2BroadPhase
    # sorts first. Topologically sort on the `Class.static` refs each makes.
    known = {(cn, s) for cn, ci in classes.items() for s in ci.statics}
    ref_re = re.compile(r"\b(\w+)\.(\w+)\b")
    produced, remaining, ordered = set(), list(tail), []
    while remaining:
        progressed = False
        deferred = []
        for item in remaining:
            cn, s, e = item
            deps = {(a, b) for a, b in ref_re.findall(e)
                    if (a, b) in known and (a, b) != (cn, s)}
            if deps <= produced:
                ordered.append(item)
                produced.add((cn, s))
                progressed = True
            else:
                deferred.append(item)
        if not progressed:
            ordered.extend(deferred)
            print("  note: %d static initialiser(s) form a cycle, left in "
                  "source order" % len(deferred))
            break
        remaining = deferred

    out.append("\n// ---- static initialisers, hoisted past declaration order "
               "and sorted by dependency ----")
    out += ["%s.%s = %s;" % t for t in ordered]
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    text = "\n".join(out)
    open(OUT, "w", encoding="utf-8").write(text)
    print("wrote %s (%d lines)" % (os.path.abspath(OUT),
                                   len(text.split("\n"))))


if __name__ == "__main__":
    main()
